#!/usr/bin/env python3
"""The machine's routine and global tables (runtime/machine/tables.h) from
meta/, for builds without the decompilation (the player's).

usage: python3 -I tools/make_tables.py <output directory>

Writes <output directory>/tables.c with the same tables VF4debug's
tools/gen_tables.py makes from the decompilation, less what only the
development tools use: the routines' declarations and argument shapes
(the observer's call log) and which ones are hand-written assembly.
"""
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def read_tsv(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f, delimiter="\t"))


def write(out_dir, meta=os.path.join(ROOT, "meta")):
    routines = sorted((int(r["address"], 16), int(r["size"]), r["name"], r["file"])
                      for r in read_tsv(os.path.join(meta, "main", "routines.tsv")))
    globs = sorted((int(r["address"], 16), r["name"]) for r in read_tsv(os.path.join(meta, "main", "globals.tsv")))
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "tables.c")
    with open(path + ".part", "w") as f:
        f.write("/* Generated by tools/make_tables.py from meta/. Do not edit, do not commit. */\n")
        f.write('#include "tables.h"\n\n')
        f.write("const gen_routine gen_routines[] = {\n")
        for a, size, name, file in routines:
            f.write("  {0x%08xu, %d, %s, %s, 0, 0, 0},\n" % (a, size, cstr(name), cstr(file)))
        f.write("};\nconst int gen_routine_count = %d;\n\n" % len(routines))
        f.write("const gen_global gen_globals[] = {\n")
        for a, name in globs:
            f.write("  {0x%08xu, %s},\n" % (a, cstr(name)))
        f.write("};\nconst int gen_global_count = %d;\n" % len(globs))
    os.replace(path + ".part", path)
    return len(routines), len(globs)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    n, g = write(sys.argv[1])
    print("make_tables.py: %d routines, %d globals" % (n, g))


if __name__ == "__main__":
    main()

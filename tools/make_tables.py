#!/usr/bin/env python3
"""The machine's routine and global tables (runtime/machine/tables.h) from
meta/, for builds without the decompilation (the player's).

usage: python3 -I tools/make_tables.py <output directory> [--test-only]

Writes <output directory>/tables.c with the same tables VF4debug's
tools/gen_tables.py makes from the decompilation, less what only the
development tools use: the routines' declarations and argument shapes
(the observer's call log) and which ones are hand-written assembly. And
<output directory>/tables_test.c, the test program's (gen_test_routines,
gen_test_globals), which the machine switches to in test mode; with
--test-only, only that one (a build whose tables.c comes from gen_tables.py).
"""
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def read_tsv(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f, delimiter="\t"))


def write_one(out_dir, meta, program, prefix):
    routines = sorted((int(r["address"], 16), int(r["size"]), r["name"], r["file"])
                      for r in read_tsv(os.path.join(meta, program, "routines.tsv")))
    globs = sorted((int(r["address"], 16), r["name"]) for r in read_tsv(os.path.join(meta, program, "globals.tsv")))
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "tables.c" if program == "main" else "tables_%s.c" % program)
    with open(path + ".part", "w") as f:
        f.write("/* Generated by tools/make_tables.py from meta/. Do not edit, do not commit. */\n")
        f.write('#include "tables.h"\n\n')
        f.write("const gen_routine %s_routines[] = {\n" % prefix)
        for a, size, name, file in routines:
            f.write("  {0x%08xu, %d, %s, %s, 0, 0, 0},\n" % (a, size, cstr(name), cstr(file)))
        f.write("};\nconst int %s_routine_count = %d;\n\n" % (prefix, len(routines)))
        f.write("const gen_global %s_globals[] = {\n" % prefix)
        for a, name in globs:
            f.write("  {0x%08xu, %s},\n" % (a, cstr(name)))
        f.write("};\nconst int %s_global_count = %d;\n" % (prefix, len(globs)))
    os.replace(path + ".part", path)
    return len(routines), len(globs)


def write(out_dir, meta=os.path.join(ROOT, "meta"), test_only=False):
    """tables.c (main.bin) and tables_test.c (test.bin); the main program's counts"""
    r = (0, 0) if test_only else write_one(out_dir, meta, "main", "gen")
    write_one(out_dir, meta, "test", "gen_test")
    return r


def main():
    args = sys.argv[1:]
    test_only = "--test-only" in args
    args = [a for a in args if a != "--test-only"]
    if len(args) != 1:
        sys.exit(__doc__)
    n, g = write(args[0], test_only=test_only)
    print("make_tables.py: %d routines, %d globals (and the test program's)" % (n, g))


if __name__ == "__main__":
    main()

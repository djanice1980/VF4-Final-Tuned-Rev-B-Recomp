def attack(ms):
    """Per-sample multiplier (2^32 scale) taking the level from 0x280 to 1 in ms; 0 = never, 1 = at once."""
    if ms < 0:
        return 0
    if ms == 0:
        return 1
    n = 44.1 * ms
    return min(0xFFFFFFFF, round(2 ** 32 * 0x280 ** (-1 / n)))


def decay(ms):
    """Per-sample increase of the 16.16 level over the whole 0..0x3FF range in ms; 0 = never."""
    if ms < 0:
        return 0
    if ms == 0:
        return 0x3FF << 16
    return max(1, round((0x3FF << 16) / (44.1 * ms)))


def row(vals, per=6, fmt="0x{:08x}u"):
    out = []
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(fmt.format(v) for v in vals[i:i + per]) + ",")
    return "\n".join(out)



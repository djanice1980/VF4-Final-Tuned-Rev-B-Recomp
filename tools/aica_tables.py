print("/* attack: the 16.16 level is multiplied by this / 2^32 each sample (0 never, 1 at once) */")
print("static const unsigned aica_attack_mul[64] = {\n" + row([attack(m) for m in ATTACK_MS]) + "\n};\n")
print("/* decay 1, decay 2, release: added to the 16.16 level each sample (0 never) */")
print("static const unsigned aica_decay_inc[64] = {\n" + row([decay(m) for m in DSR_MS]) + "\n};\n")
gain = [int(32768 / 2 ** (i / 16)) for i in range(256)]
print("/* attenuation in 1/16 octave -> gain, 32768 = 1 (255 and above: silent) */")
print("static const unsigned short aica_gain[256] = {\n" + row(gain, 12, "{:5d}") + "\n};\n")
print("#endif")

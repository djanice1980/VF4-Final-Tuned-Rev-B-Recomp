#!/usr/bin/env python3
"""Single-instruction test cases for tests/lockstep/lockstep.c.

usage: python3 -I tests/lockstep/gen_cases.py <out-dir>

Every 16-bit word the decoder takes for an ordinary instruction (not a
branch, trapa or sleep) becomes a C function holding exactly what the
translator emits for it, placed at CODE: once if the FPU mode does not
matter to it, else once for each value of the mode bit it reads (SZ or PR)
and once with the mode tested at run time. PC-relative loads read a pool of
fixed pseudo-random bytes after CODE, the same bytes the harness writes to
guest memory.

Writes <out-dir>/insn_cases.c (the functions, a table of them, the pool).
"""
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "translator"))
import sh4dec as D          # noqa: E402
import translate as T       # noqa: E402

CODE = 0x0C900000
POOL = 0x600                # bytes after CODE the pool covers (pc + 4 + 1020 at most)


class Pool:
    """Stands in for the program image: literal() as Program has it."""
    def __init__(self, data):
        self.data = data

    def literal(self, a, size):
        o = a - CODE
        if o < 4 or o + max(size, 1) > len(self.data):
            return None
        if size == 4:
            return int.from_bytes(self.data[o:o + 4], "little")
        if size == 2:
            v = int.from_bytes(self.data[o:o + 2], "little")
            return (v - 0x10000 if v & 0x8000 else v) & 0xFFFFFFFF
        return a


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    rng = random.Random(0x5A4F)
    pool = bytearray(rng.getrandbits(8) for _ in range(POOL))
    prog = Pool(pool)
    funcs, rows = [], []
    kinds = {}
    for op in range(0x10000):
        i = D.decode(op, CODE)
        if i.kind != D.NORMAL:
            kinds[i.kind] = kinds.get(i.kind, 0) + 1
            continue
        if i.mode is None:
            variants = [(-1, (T.UNK, T.UNK))]
        elif i.mode == "sz":
            variants = [(0, (0, T.UNK)), (1, (1, T.UNK)), (2, (T.UNK, T.UNK))]
        else:
            variants = [(0, (T.UNK, 0)), (1, (T.UNK, 1)), (2, (T.UNK, T.UNK))]
        for v, mode in variants:
            lines = T.emit_insn(prog, i, mode)
            if any("rt_illegal" in ln for ln in lines):
                continue        # an instruction the chip does not define in this mode
            name = f"x_{op:04x}_{v + 1}"
            funcs.append(f"static void {name}(sh4 *restrict c)  /* {i.text} */\n{{\n    RT_COUNT(c, 1);\n"
                         + "".join(f"    {ln}\n" for ln in lines) + "}\n")
            mem = "@" in i.text
            idx = "@(r0," in i.text
            field = {"sz": 1, "pr": 2}.get(i.mode, 0)
            rows.append(f"    {{ 0x{op:04x}, {v}, {field}, {int(mem)}, {int(idx)}, {name}, \"{i.text}\" }},")
    src = ['/* Generated by tests/lockstep/gen_cases.py: do not edit. */',
           '#include "sh4rt.h"',
           '#include "lockstep_cases.h"',
           '']
    src += funcs
    src.append(f"const insn_case insn_cases[] = {{\n" + "\n".join(rows) + "\n};")
    src.append(f"const unsigned insn_case_count = {len(rows)};")
    src.append(f"const unsigned char insn_pool[{POOL}] = {{" + ",".join(str(b) for b in pool) + "};")
    src.append(f"const unsigned insn_pool_size = {POOL};")
    src.append(f"const unsigned insn_code_addr = 0x{CODE:08x}u;")
    src.append("")
    src.append("/* the host side of a state change made outside translated code */")
    src.append("void case_fpscr_loaded(sh4 *c) { rt_set_mxcsr_for(c->fpscr); }")
    with open(os.path.join(out, "insn_cases.c"), "w") as f:
        f.write("\n".join(src) + "\n")
    print(f"{len(rows)} cases from {len(set(r.split(',')[0] for r in rows))} opcodes; not ordinary: {kinds}")


if __name__ == "__main__":
    main()
